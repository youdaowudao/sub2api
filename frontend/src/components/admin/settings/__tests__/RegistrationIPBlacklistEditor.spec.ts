import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import RegistrationIPBlacklistEditor from '../RegistrationIPBlacklistEditor.vue'

const mocks = vi.hoisted(() => ({ get: vi.fn(), save: vi.fn(), success: vi.fn() }))
vi.mock('@/api', () => ({ adminAPI: { settings: {
  getRegistrationIPBlacklist: mocks.get, updateRegistrationIPBlacklist: mocks.save
} } }))
vi.mock('@/stores', () => ({ useAppStore: () => ({ showSuccess: mocks.success }) }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))

const mountEditor = () => mount(RegistrationIPBlacklistEditor, { global: { stubs: { teleport: true } } })
const selector = (suffix: string) => `[data-testid="ip-blacklist-${suffix}"]`
beforeEach(() => {
  vi.resetAllMocks()
  mocks.get.mockResolvedValue({ ips: ['192.0.2.1'] })
  mocks.save.mockResolvedValue({ ips: ['2001:db8::1'] })
})

describe('RegistrationIPBlacklistEditor', () => {
  it('only loads on opening, independently saves, and does not reread after success', async () => {
    const wrapper = mountEditor()
    expect(mocks.get).not.toHaveBeenCalled()
    await wrapper.get(selector('edit')).trigger('click')
    await flushPromises()
    expect(mocks.get).toHaveBeenCalledTimes(1)
    expect((wrapper.get(selector('draft')).element as HTMLTextAreaElement).value).toBe('192.0.2.1')
    await wrapper.get(selector('draft')).setValue(' 2001:0db8::1 \n\n')
    await wrapper.get(selector('save')).trigger('click')
    await flushPromises()
    expect(mocks.save).toHaveBeenCalledTimes(1)
    expect(mocks.save).toHaveBeenCalledWith(['2001:0db8::1'])
    expect(mocks.get).toHaveBeenCalledTimes(1)
    expect(mocks.success).toHaveBeenCalledTimes(1)
    wrapper.unmount()
  })

  it('blocks save before successful load, then allows explicit clearing of invalid settings', async () => {
    mocks.get.mockRejectedValueOnce({ message: 'read failed' }).mockResolvedValueOnce({ ips: null })
    const wrapper = mountEditor()
    await wrapper.get(selector('edit')).trigger('click')
    await flushPromises()
    expect(wrapper.get(selector('save')).attributes('disabled')).toBeDefined()
    expect(wrapper.text()).toContain('read failed')
    await wrapper.get(selector('reload')).trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('invalidStored')
    expect(wrapper.get(selector('save')).attributes('disabled')).toBeUndefined()
    mocks.save.mockResolvedValueOnce({ ips: [] })
    await wrapper.get(selector('save')).trigger('click')
    await flushPromises()
    expect(mocks.save).toHaveBeenCalledTimes(1)
    expect(mocks.save).toHaveBeenCalledWith([])
    wrapper.unmount()
  })

  it('preserves draft on validation and uncertain save errors, requires a successful manual reload', async () => {
    const wrapper = mountEditor()
    await wrapper.get(selector('edit')).trigger('click')
    await flushPromises()
    await wrapper.get(selector('draft')).setValue('invalid')
    mocks.save.mockRejectedValueOnce({ reason: 'REGISTRATION_IP_BLACKLIST_INVALID', message: 'invalid address' })
    await wrapper.get(selector('save')).trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('invalid address')
    expect(wrapper.get(selector('save')).attributes('disabled')).toBeUndefined()
    expect((wrapper.get(selector('draft')).element as HTMLTextAreaElement).value).toBe('invalid')
    await wrapper.get(selector('draft')).setValue('192.0.2.2')
    mocks.save.mockRejectedValueOnce({ message: 'connection lost' })
    await wrapper.get(selector('save')).trigger('click')
    await flushPromises()
    expect(wrapper.text()).toContain('unknownSave')
    expect(wrapper.text()).toContain('connection lost')
    expect(wrapper.get(selector('save')).attributes('disabled')).toBeDefined()
    mocks.get.mockRejectedValueOnce({ message: 'reload failed' })
    await wrapper.get(selector('reload')).trigger('click')
    await flushPromises()
    expect((wrapper.get(selector('draft')).element as HTMLTextAreaElement).value).toBe('192.0.2.2')
    expect(wrapper.get(selector('save')).attributes('disabled')).toBeDefined()
    expect(wrapper.text()).toContain('connection lost')
    expect(wrapper.text()).toContain('reload failed')
    await wrapper.get(selector('reload')).trigger('click')
    await flushPromises()
    expect((wrapper.get(selector('draft')).element as HTMLTextAreaElement).value).toBe('192.0.2.1')
    expect(wrapper.get(selector('save')).attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })
  it('cancels a changed draft without writing and prevents duplicate save while pending', async () => {
    const wrapper = mountEditor()
    await wrapper.get(selector('edit')).trigger('click')
    await flushPromises()
    await wrapper.get(selector('draft')).setValue('192.0.2.2')
    const cancel = wrapper.findAll('button').find(button => button.text() === 'common.cancel')
    expect(cancel).toBeDefined()
    await cancel!.trigger('click')
    expect(mocks.save).not.toHaveBeenCalled()
    await wrapper.get(selector('edit')).trigger('click')
    await flushPromises()
    expect((wrapper.get(selector('draft')).element as HTMLTextAreaElement).value).toBe('192.0.2.1')
    let resolveSave!: (value: { ips: string[] }) => void
    mocks.save.mockReturnValueOnce(new Promise(resolve => { resolveSave = resolve }))
    await wrapper.get(selector('save')).trigger('click')
    expect(wrapper.get(selector('draft')).attributes('disabled')).toBeDefined()
    await wrapper.get(selector('save')).trigger('click')
    expect(mocks.save).toHaveBeenCalledTimes(1)
    resolveSave({ ips: ['192.0.2.1'] })
    await flushPromises()
    expect(mocks.success).toHaveBeenCalledTimes(1)
    wrapper.unmount()
  })

})
