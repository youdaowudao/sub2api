const openEditDialog = async (group: AdminGroup) => {
  listGroups.mockResolvedValue({
    items: [group],
    total: 1,
    page: 1,
    page_size: 20,
    pages: 1,
  });
  const wrapper = mountView();
  await flushPromises();
  const editButton = wrapper
    .findAll("button")
    .find((button) => button.text().includes("common.edit"));
  expect(editButton).toBeTruthy();
  await editButton!.trigger("click");
  await flushPromises();
  return wrapper;
};


describe("GroupsView routing order round trip", () => {
  beforeEach(() => {
    localStorage.clear();
    vi.clearAllMocks();
    getModelAllowlistCandidates.mockResolvedValue([]);
    getUsageSummary.mockResolvedValue([]);
    getCapacitySummary.mockResolvedValue([]);
    getLiveCapability.mockResolvedValue({ supported: false });
    updateGroup.mockResolvedValue({});
  });

  const patternInputs = (wrapper: ReturnType<typeof mountView>) =>
    wrapper.findAll<HTMLInputElement>('input[placeholder="admin.groups.modelRouting.modelPatternPlaceholder"]');
  const group = {
    ...sourceGroup,
    platform: "anthropic" as const,
    model_routing_enabled: true,
    model_routing: { a: [11], z: [22], m: [33] },
    model_routing_order: ["z", "a", "m"],
  };
  async function save(wrapper: ReturnType<typeof mountView>) {
    await wrapper.get("#edit-group-form").trigger("submit");
    await flushPromises();
    return updateGroup.mock.lastCall![1];
  }

  it("deleting all routing rows submits an empty map rather than null", async () => {
    const wrapper = await openEditDialog(group);
    for (const button of wrapper.findAll('button[title="admin.groups.modelRouting.removeRule"]')) {
      await button.trigger("click");
    }
    expect(patternInputs(wrapper)).toHaveLength(0);
    const request = await save(wrapper);
    expect(request.model_routing).toEqual({});
    expect(request.model_routing_order).toEqual([]);
    wrapper.unmount();
  });

  it("keeps the saved order and pairs after two saves and reopens", async () => {
    let persisted: AdminGroup = group;
    for (let i = 0; i < 3; i++) {
      const wrapper = await openEditDialog(persisted);
      expect(patternInputs(wrapper).map(input => input.element.value)).toEqual(["z", "a", "m"]);
      if (i < 2) {
        const request = await save(wrapper);
        expect(request.model_routing).toEqual(group.model_routing);
        expect(request.model_routing_order).toEqual(group.model_routing_order);
        persisted = { ...persisted, ...request };
      }
      wrapper.unmount();
    }
  });

  it("sorts older data deterministically", async () => {
    const wrapper = await openEditDialog({ ...group, model_routing_order: null });
    expect(patternInputs(wrapper).map(input => input.element.value)).toEqual(["a", "m", "z"]);
    wrapper.unmount();
  });
});
